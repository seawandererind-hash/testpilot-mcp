/** Plans the .gitignore lines TestPilot needs (secrets and test output), keeping everything already there. */
export function planGitignore(store: ProjectStore, lines: string[]): PlannedFile {
    const current = store.read('.gitignore');
    const have = new Set((current ?? '').split(/\r?\n/).map(l => l.trim()));
    const missing = lines.filter(line => !have.has(line));
    if (!missing.length) return { path: '.gitignore', status: 'unchanged', content: current ?? '' };
    const base = current ? `${current.replace(/\s*$/, '')}\n\n` : '';
    const content = `${base}# Added by TestPilot MCP\n${missing.join('\n')}\n`;
    return current === undefined ? { path: '.gitignore', status: 'new', content } : { path: '.gitignore', status: 'merge', content, note: `Adds ${missing.join(', ')}.` };
}
