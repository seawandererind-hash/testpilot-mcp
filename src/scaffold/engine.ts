import { spawn } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

import Handlebars from 'handlebars';

import { toPosix } from '../core/paths.js';
import type { Config } from '../core/schema.js';
import type { ProjectStore } from '../core/store.js';
import { PACKAGE_ROOT } from '../package-root.js';

/** Marks Markdown that TestPilot owns and regenerates (AGENTS.md, skills, rules). */
export const GENERATED_HEADER = 'generated by TestPilot; edit .testpilot/config.yaml instead';
/** Marks code TestPilot created once; from then on it belongs to the team. */
export const CREATED_HEADER = 'Created by TestPilot. This file is yours: edit it freely.';

/** Folder holding template packs, next to dist/ or src/ in the installed package. */
export const TEMPLATES_DIR = path.join(PACKAGE_ROOT, 'templates');

/** Reads a bundled template with LF line endings, so output is the same when git checked the templates out with CRLF. */
export function readTemplate(file: string): string {
    return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

/** Conditions a pack entry can depend on; a list means all of them must hold. */
export type When = 'ui' | 'web' | 'api' | 'electron' | 'mobile' | 'android' | 'ios' | 'desktop' | 'windows' | 'macos' | 'wincore' | 'novawindows' | 'local' | 'cloud';

interface PackFile {
    from: string;
    to: string;
    when?: When | When[];
    ifMissing?: boolean;
}

export interface PackManifest {
    id: string;
    title: string;
    appTypes: string[];
    patterns: string[];
    devDependencies: Record<string, string>;
    /** Extra packages keyed by a reporting choice, an extra, or the execution target (e.g. "browserstack"). */
    optionalDevDependencies?: Record<string, Record<string, string>>;
    scripts: Record<string, string | { run: string; when: When | When[] }>;
    install: Array<string[] | { argv: string[]; when?: When | When[] }>;
    /** Steps TestPilot cannot do for the user (SDKs, drivers, devices), shown in the scaffold preview. */
    manualSetup?: Array<{ text: string; when?: When | When[] }>;
    files: PackFile[];
}

export type FileStatus = 'new' | 'unchanged' | 'conflict' | 'merge' | 'skip';

export interface PlannedFile {
    path: string;
    status: FileStatus;
    content: string;
    note?: string;
}

export function loadPack(id: string): PackManifest {
    const file = path.join(TEMPLATES_DIR, id, 'manifest.json');
    if (!existsSync(file)) throw new Error(`Template pack "${id}" is not installed.`);
    return JSON.parse(readFileSync(file, 'utf8')) as PackManifest;
}

export function renderContext(config: Config): Record<string, unknown> {
    const appType = config.appType ?? 'web';
    const browsers = (config.execution.browsers?.length ? config.execution.browsers : ['chromium']).map(name => ({
        name,
        device: name === 'firefox' ? 'Desktop Firefox' : name === 'webkit' ? 'Desktop Safari' : 'Desktop Chrome'
    }));
    const reporting = new Set(config.integrations.reporting ?? ['html', 'junit']);
    return {
        header: CREATED_HEADER,
        config,
        appType,
        isWeb: appType === 'web',
        isApi: appType === 'api',
        isElectron: appType === 'electron',
        isMobile: ['android', 'ios', 'android-ios', 'hybrid'].includes(appType),
        isAndroid: ['android', 'android-ios', 'hybrid'].includes(appType),
        isIos: ['ios', 'android-ios'].includes(appType),
        isDesktop: ['windows', 'macos'].includes(appType),
        isWindows: appType === 'windows',
        isMacos: appType === 'macos',
        isAndroidIos: appType === 'android-ios',
        isNovaWindows: appType === 'windows' && config.stack.framework === 'appium-novawindows',
        automationName: automationNameFor(config),
        browsers,
        reporting: { html: reporting.has('html'), junit: reporting.has('junit'), allure: reporting.has('allure') },
        cloud: config.execution.target === 'browserstack',
        projectName: config.project.name ?? 'app',
        projectNameJson: JSON.stringify(config.project.name ?? 'app')
    };
}

function automationNameFor(config: Config): string {
    switch (config.appType) {
        case 'ios':
            return 'XCUITest';
        case 'macos':
            return 'Mac2';
        case 'windows':
            return config.stack.framework === 'appium-novawindows' ? 'NovaWindows' : 'Wincore';
        default:
            return 'UiAutomator2';
    }
}

function applies(when: When | When[] | undefined, ctx: Record<string, unknown>): boolean {
    if (Array.isArray(when)) return when.every(w => applies(w, ctx));
    switch (when) {
        case undefined:
            return true;
        case 'ui':
            return !ctx.isApi;
        case 'web':
            return Boolean(ctx.isWeb);
        case 'api':
            return Boolean(ctx.isApi);
        case 'electron':
            return Boolean(ctx.isElectron);
        case 'mobile':
            return Boolean(ctx.isMobile);
        case 'android':
            return Boolean(ctx.isAndroid);
        case 'ios':
            return Boolean(ctx.isIos);
        case 'desktop':
            return Boolean(ctx.isDesktop);
        case 'windows':
            return Boolean(ctx.isWindows);
        case 'macos':
            return Boolean(ctx.isMacos);
        case 'wincore':
            return Boolean(ctx.isWindows) && !ctx.isNovaWindows;
        case 'novawindows':
            return Boolean(ctx.isNovaWindows);
        case 'local':
            return !ctx.cloud;
        case 'cloud':
            return Boolean(ctx.cloud);
    }
}

/** The install commands of a pack that apply to this setup. */
export function installCommandsFor(pack: PackManifest, config: Config): string[][] {
    const ctx = renderContext(config);
    return pack.install.map(entry => (Array.isArray(entry) ? { argv: entry } : entry)).filter(entry => applies(entry.when, ctx)).map(entry => entry.argv);
}

/** Manual setup steps of a pack that apply to this setup, as one numbered text (undefined when there are none). */
export function manualSetupFor(pack: PackManifest, config: Config): string | undefined {
    const ctx = renderContext(config);
    const steps = (pack.manualSetup ?? []).filter(step => applies(step.when, ctx)).map(step => step.text);
    return steps.length ? steps.map((text, i) => `${i + 1}. ${text}`).join('\n') : undefined;
}

const templateCache = new Map<string, HandlebarsTemplateDelegate>();

export function renderTemplate(packId: string, from: string, ctx: Record<string, unknown>): string {
    const file = path.join(TEMPLATES_DIR, packId, 'files', from);
    let template = templateCache.get(file);
    if (!template) {
        template = Handlebars.compile(readTemplate(file), { noEscape: true, strict: false });
        templateCache.set(file, template);
    }
    return template(ctx);
}

/** Joins the configured test root with a pack-relative path. */
export function inTestRoot(config: Config, relative: string): string {
    const root = config.project.testRoot && config.project.testRoot !== '.' ? config.project.testRoot : '';
    return toPosix(path.posix.join(root, relative));
}

/** Works out every file a pack would write, compared with what is on disk. */
export function planPack(store: ProjectStore, config: Config, packId: string): { pack: PackManifest; files: PlannedFile[] } {
    const pack = loadPack(packId);
    const ctx = renderContext(config);
    const files: PlannedFile[] = [];
    for (const f of pack.files) {
        if (!applies(f.when, ctx)) continue;
        const target = inTestRoot(config, f.to);
        const content = renderTemplate(packId, f.from, ctx);
        files.push(compareWithDisk(store, target, content, f.ifMissing));
    }
    files.push(planPackageJson(store, config, pack, ctx));
    return { pack, files };
}

export function compareWithDisk(store: ProjectStore, target: string, content: string, ifMissing = false): PlannedFile {
    const current = store.read(target);
    if (current === undefined) return { path: target, status: 'new', content };
    if (current === content) return { path: target, status: 'unchanged', content };
    if (ifMissing) return { path: target, status: 'skip', content, note: 'Already exists; kept as is.' };
    return { path: target, status: 'conflict', content, note: 'A different version exists. It is kept unless you list it in overwrite.' };
}

/** Adds dependencies and scripts to package.json without changing anything already there. */
export function planPackageJson(store: ProjectStore, config: Config, pack: PackManifest, ctx: Record<string, unknown> = renderContext(config)): PlannedFile {
    const target = inTestRoot(config, 'package.json');
    const current = store.read(target);
    const pkg = current ? JSON.parse(current) : { name: `${(config.project.name ?? 'app').toLowerCase().replace(/[^a-z0-9-]+/g, '-')}-tests`, version: '1.0.0', private: true };
    pkg.devDependencies ??= {};
    pkg.scripts ??= {};
    const added: string[] = [];
    const deps = { ...pack.devDependencies };
    for (const [feature, extra] of Object.entries(pack.optionalDevDependencies ?? {})) {
        if (config.integrations.reporting?.includes(feature) || config.extras.includes(feature) || config.execution.target === feature) Object.assign(deps, extra);
    }
    for (const [name, version] of Object.entries(deps)) {
        if (!pkg.devDependencies[name] && !pkg.dependencies?.[name]) {
            pkg.devDependencies[name] = version;
            added.push(name);
        }
    }
    for (const [name, entry] of Object.entries(pack.scripts)) {
        if (typeof entry !== 'string' && !applies(entry.when, ctx)) continue;
        const script = typeof entry === 'string' ? entry : entry.run;
        const key = pkg.scripts[name] && pkg.scripts[name] !== script ? `tp:${name}` : name;
        if (!pkg.scripts[key]) {
            pkg.scripts[key] = script;
            added.push(`script ${key}`);
        }
    }
    const content = JSON.stringify(pkg, null, 2) + '\n';
    if (!current) return { path: target, status: 'new', content };
    return added.length ? { path: target, status: 'merge', content, note: `Adds ${added.join(', ')}; keeps everything already there.` } : { path: target, status: 'unchanged', content };
}

/** Writes planned files. Conflicts are written only when listed in `overwrite`. */
export function writePlanned(store: ProjectStore, files: PlannedFile[], overwrite: string[] = []): { written: string[]; kept: string[] } {
    const written: string[] = [];
    const kept: string[] = [];
    for (const f of files) {
        if (f.status === 'new' || f.status === 'merge' || (f.status === 'conflict' && overwrite.includes(f.path))) {
            store.write(f.path, f.content);
            written.push(f.path);
        } else if (f.status === 'conflict' || f.status === 'skip') {
            kept.push(f.path);
        }
    }
    return { written, kept };
}

export interface CommandOutcome {
    command: string;
    ok: boolean;
    exitCode: number | null;
    tail: string;
}

/** Runs a command in the project, returning the last lines of output. */
export function runCommand(cwd: string, argv: string[], timeoutMs = 10 * 60 * 1000, env: NodeJS.ProcessEnv = process.env): Promise<CommandOutcome> {
    return new Promise(resolve => {
        const [cmd, ...args] = argv;
        const child = spawn(cmd, args, { cwd, env, shell: process.platform === 'win32', windowsHide: true });
        let out = '';
        const keep = (chunk: Buffer) => {
            out = (out + chunk.toString()).slice(-8000);
        };
        child.stdout.on('data', keep);
        child.stderr.on('data', keep);
        const timer = setTimeout(() => child.kill('SIGTERM'), timeoutMs);
        child.on('error', error => {
            clearTimeout(timer);
            resolve({ command: argv.join(' '), ok: false, exitCode: null, tail: String(error.message) });
        });
        child.on('close', code => {
            clearTimeout(timer);
            resolve({ command: argv.join(' '), ok: code === 0, exitCode: code, tail: out.split(/\r?\n/).slice(-25).join('\n') });
        });
    });
}

